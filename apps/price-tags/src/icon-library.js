// 当前分类下的图标与分组
export function getBuiltinIcons(category) {
  return BUILTIN_ICONS_BY_CATEGORY[category] || BUILTIN_ICONS_BY_CATEGORY['笔记本'] || []
}

export function iconCategoriesOf(category) {
  const icons = getBuiltinIcons(category)
  return [...new Set(icons.map((icon) => icon.category))]
}

export function getIconSrc(name, category) {
  if (!name) return ''
  const icon = getBuiltinIcons(category).find((item) => item.name === name)
  return icon ? icon.src : ''
}
